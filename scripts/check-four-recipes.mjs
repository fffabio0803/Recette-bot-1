import fs from 'node:fs';
import assert from 'node:assert/strict';
await import('../assets/placard-match.js');
const read = f => fs.readFileSync(f, 'utf8');
const catalogue = JSON.parse(read('recettes.json')).recettes;
const names = ["pates-creme-parmesan","pois-chiches-epinards-curry","soupe-carottes-lentilles-corail","gateau-yaourt-poires"];
const terms = [['pâtes','crème','parmesan'],['pois chiches','épinards','curry'],['carottes','lentilles corail'],['yaourt','poires']];
const tools = read('outils.html');
const script = [...tools.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(m=>m[1]).find(s=>s.includes('function placard(recipes)'));
const pantry = JSON.parse(script.slice(script.lastIndexOf('})([')+3).replace(/\);\s*$/,''));
const migration = read('supabase/migrations/20261119_four_recipe_targets.sql');
const images = new Set();
for (let i=0;i<names.length;i++) {
 const slug=names[i], r=catalogue.find(x=>x.slug===slug);
 assert.ok(r);
 const html=read(r.url);
 const schema=JSON.parse(html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1]);
 assert.equal(schema.name,r.title);
 assert.equal(schema.recipeYield,r.yield_label);
 assert.equal(schema.aggregateRating,undefined);
 assert.equal(schema.nutrition,undefined);
 assert.ok(html.includes('sans essai culinaire documenté'));
 assert.ok(html.includes('illustration générée'));
 const ingredients=[...html.match(/<h2 id="ingredients">Ingrédients<\/h2><ul>(.*?)<\/ul>/)[1].matchAll(/<li>(.*?)<\/li>/g)].map(m=>m[1]);
 assert.deepEqual(schema.recipeIngredient,ingredients);
 const steps=[...html.matchAll(/<li id="etape-\d+">(.*?)<\/li>/g)].map(m=>m[1]);
 assert.deepEqual(schema.recipeInstructions.map(s=>s.text),steps);
 schema.recipeInstructions.forEach((s,n)=>assert.ok(s.url.endsWith('#etape-'+(n+1))));
 const image=schema.image.replace('https://latablemijote.fr/','');
 assert.ok(fs.statSync(image).size<400000);
 images.add(image);
 for(const file of ['index.html','toutes-les-recettes.html','sitemap.xml'])assert.ok(read(file).includes(r.url), file+': '+slug);
 assert.ok(migration.includes("('"+slug+"', true)"));
 const found=globalThis.LTMPlacard.rank(pantry,terms[i]);
 assert.equal(found[0].r.url,'/'+r.url,terms[i].join('+'));
 assert.equal(found[0].percent,100);
 assert.deepEqual(pantry.find(x=>x.url==='/'+r.url).ingredients,schema.recipeIngredient);
}
assert.equal(images.size,4);
assert.equal(globalThis.LTMPlacard.canonical('marrons'),globalThis.LTMPlacard.canonical('châtaignes'));
assert.ok(!globalThis.LTMPlacard.matches('crème de marrons','crème liquide'));
assert.ok(read('assets/placard-ui.js').includes("'Potimarron'"));
assert.ok(read('toutes-les-recettes.html').includes('"Soupes"'));
console.log('Lot du 19 novembre : 4 fiches, étapes, images, avis et recherches pertinentes à 100 % contrôlés.');
