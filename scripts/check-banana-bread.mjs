import fs from 'node:fs';
import assert from 'node:assert/strict';
const slug = 'banana-bread-quatre-epices';
const html = fs.readFileSync('recettes/' + slug + '.html', 'utf8');
const recipe = JSON.parse(html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1]);
const entry = JSON.parse(fs.readFileSync('recettes.json', 'utf8')).recettes.find(r => r.slug === slug);
assert.equal(recipe.cookTime, 'PT35M');
assert.equal(recipe.recipeYield, '1 cake');
assert.equal(entry.servings, null);
assert.equal(entry.time_uncertain, true);
for (const key of ['prepTime', 'totalTime', 'aggregateRating']) assert.equal(recipe[key], undefined);
for (const item of recipe.recipeIngredient) assert.ok(html.includes('<li>' + item + '</li>'), item);
assert.equal(recipe.recipeInstructions.length, 7);
for (const step of recipe.recipeInstructions) assert.ok(html.includes('id="' + step.url.split('#')[1] + '"'));
assert.ok(html.includes('Variantes proposées, non testées'));
assert.ok(html.includes('poids du sachet non renseigné'));
for (const name of ['tranche', 'moule']) assert.ok(fs.statSync('assets/images/recipes/banana-bread-' + name + '.jpg').size > 1000);
assert.ok(fs.readFileSync('supabase/migrations/20261021_banana_review_target.sql','utf8').includes(slug));
console.log('Banana bread : retour réel, incertitudes, images et données structurées cohérents.');
