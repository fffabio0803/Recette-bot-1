import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source = fs.readFileSync('assets/analytics-consent.js', 'utf8');
const window = {addEventListener() {}};
vm.runInNewContext(source, {window, document: {readyState: 'loading', addEventListener() {}}});
const events = () => window.dataLayer.filter(x => x[0] === 'event');
window.ltmTrack('placard_search', {ingredient_count: 2, result_count: 3});
assert.equal(events().length, 0, 'No analytics event before consent');
window['ga-disable-G-RD4N5W9HP7'] = false;
window.ltmTrack('placard_search', {ingredient_count: 2, result_count: 3, ingredients: 'private text'});
assert.equal(events().length, 1);
assert.equal(events()[0][2].ingredient_count, 2);
assert.equal(events()[0][2].ingredients, undefined);
window.ltmTrack('recipe_review_saved', {recipe_slug: 'cookies-moelleux-chocolat', comment: 'private', email: 'private'});
assert.equal(events()[1][2].recipe_slug, 'cookies-moelleux-chocolat');
assert.equal(events()[1][2].comment, undefined);
assert.equal(events()[1][2].email, undefined);
window.ltmTrack('unknown_event', {});
assert.equal(events().length, 2);
window.ltmTrack('placard_recipe_open', {recipe_slug: 'private@email.invalid'});
assert.equal(events()[2][2].recipe_slug, undefined);
window['ga-disable-G-RD4N5W9HP7'] = true;
window.ltmTrack('placard_search', {ingredient_count: 3});
assert.equal(events().length, 3, 'Consent revocation stops events immediately');
const home = fs.readFileSync('index.html', 'utf8');
assert.ok(home.includes('Quoi cuisiner avec mes ingrédients ?'));
assert.ok(!home.includes('Convertir portions et moules'));
const fn = home.match(/function renderRecipeSections\(\) \{[\s\S]*?\n    \}/)[0];
const recipes = JSON.parse(fs.readFileSync('recettes.json', 'utf8')).recettes;
const context = {allRecipes: recipes, currentCategory: 'Toutes', featuredSubtitle: {}, featuredGrid: {}, latestList: {}, recipeCard: r => r.slug + '|', latestRecipe: r => r.slug + '|'};
vm.runInNewContext(fn + ';renderRecipeSections();', context);
assert.ok(context.featuredGrid.innerHTML.includes('cookies-moelleux-chocolat'));
assert.ok(context.featuredGrid.innerHTML.includes('boeuf-bourguignon'));
assert.equal(context.latestList.innerHTML.includes('cookies-moelleux-chocolat'), false);
context.currentCategory = 'Desserts';
vm.runInNewContext('renderRecipeSections();', context);
assert.ok(context.featuredGrid.innerHTML);
console.log('Accueil : priorité cookies/bourguignon et filtres OK ; événements sans données personnelles et sous consentement OK.');
